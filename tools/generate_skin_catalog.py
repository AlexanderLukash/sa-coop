"""Generate native metadata from the launcher's shared skin catalog."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
skins = json.loads((root / 'launcher/src/skins.json').read_text(encoding='utf-8'))
assert [s['id'] for s in skins] == [i for i in range(300) if i != 74]
lines = ['#pragma once', '// Generated by tools/generate_skin_catalog.py; edit launcher/src/skins.json.',
         '#include <cstddef>', 'namespace coop::skins {',
         'struct Skin { int id; const char* name; const char* model; bool special; };',
         'inline constexpr Skin kCatalog[] = {']
for skin in skins:
    lines.append('    {%d, %s, %s, %s},' % (skin['id'], json.dumps(skin['name']),
                 json.dumps(skin['model']), str(skin['special']).lower()))
lines += ['};', 'inline const Skin* Find(int id) { for (const auto& skin : kCatalog) if (skin.id == id) return &skin; return nullptr; }',
          '} // namespace coop::skins']
(root / 'src/client/shared/game/SkinCatalog.h').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Generated {len(skins)} native skins')
